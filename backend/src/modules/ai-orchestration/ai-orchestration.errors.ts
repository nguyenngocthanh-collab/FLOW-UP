export type AIErrorCode =
  | "AI_UNAUTHENTICATED" | "AI_ACCESS_DENIED" | "AI_INVALID_REQUEST"
  | "AI_INVALID_OPERATION" | "AI_CONTEXT_NOT_FOUND" | "AI_CONTEXT_ACCESS_DENIED"
